import crypto from 'node:crypto';
const sha=v=>crypto.createHash('sha256').update(String(v)).digest('hex');
const positive=v=>Number.isSafeInteger(v)&&v>0;
/** Metadata-only observer of trusted native events + host-owned receipt table. Never reads content. Trigger classification never uses a message source label. */
export function createNativeOrigin({agent,lookupReceipt}){
 const lifecycle=crypto.randomUUID();let turn=null,step=null,turnSeq=null,frame=null,closed=false,foreign=false;
 const receipts=new Map(),disposers=[];
 function sessionEvent(session,event){
  if(closed||session!==agent.session)return;
  if(event.type==='turn/start'){
   turn=positive(event.data.turn)?event.data.turn:null;step=null;turnSeq=Number.isSafeInteger(event.seq)?event.seq:null;
   frame=null;foreign=false;receipts.clear();return;
  }
  if(event.type==='turn/end'&&event.data.turn===turn){turn=null;step=null;frame=null;receipts.clear();return;}
  if(!turn)return;
  if(event.type==='step/start'){step=positive(event.data.step)?event.data.step:null;frame=null;return;}
  if(event.type!=='user/message')return;
  const receipt=lookupReceipt(event.data.id);
  if(!receipt){
   // rc.4 loop-owned runtime snapshot is not an input trigger. This exemption never grants an origin.
   if(event.data.source?.kind!=='runtime-context')foreign=true;return;
  }
  if(!['incoming','proactive'].includes(receipt.kind)){foreign=true;return;}
  // Identifier was generated by bridge issue/followup, not supplied by a model.
  receipts.set(sha(event.data.id),receipt.kind==='proactive'?'wake':'natural_user');
 }
 function assistantStream(payload){
  if(closed||payload.agent!==agent)return;
  const f=payload.frame;if(!f)return;
  if(f.type==='start'){
   frame=positive(f.turn)&&positive(f.step)&&f.turn===turn&&f.step===step&&typeof f.attemptId==='string'
    ?{turn:f.turn,step:f.step,attempt:sha(lifecycle+'\0'+f.attemptId)}:null;
  }else if(f.type==='end')frame=null;
 }
 function snapshot(){
  if(closed||!frame||!turn||turnSeq===null||!receipts.size||foreign||receipts.size>8)return null;
  const kinds=new Set(receipts.values()),trigger=kinds.size===1?[...kinds][0]:'mixed';
  return {target_category:'owner_private',trigger_type:trigger,native_turn:frame.turn,native_step:frame.step,
   native_turn_event_seq:turnSeq,native_attempt_hash:frame.attempt,agent_lifecycle:lifecycle,
   source_receipt_hashes:[...receipts.keys()].sort(),link_status:trigger==='mixed'?'mixed_host_receipts':'host_receipt_and_native_attempt'};
 }
 return {sessionEvent,assistantStream,snapshot,attach(ctx){
  if(typeof ctx.on!=='function')return;
  const a=ctx.on('session/event',sessionEvent),b=ctx.on('agent/assistant-stream',assistantStream);
  if(typeof a==='function')disposers.push(a);if(typeof b==='function')disposers.push(b);
 },close(){if(closed)return;closed=true;frame=null;turn=null;receipts.clear();for(const d of disposers.splice(0))d();}};
}
